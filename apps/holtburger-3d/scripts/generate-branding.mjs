#!/usr/bin/env node
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";
import { Resvg } from "@resvg/resvg-js";
import png2icons from "png2icons";
import postcss from "postcss";
import { format } from "prettier";

const repository = new URL("../../../", import.meta.url);
const { values } = parseArgs({ options: { check: { type: "boolean" } } });
const check = values.check === true;
const source = await readFile(
	new URL("assets/branding/portal.svg", repository),
	"utf8",
);

// Freeze the authored reduced-motion geometry while retaining its base styles.
// Removing keyframes also keeps CSS path animation out of non-browser SVG readers.
const style = source.match(/<style>([\s\S]*?)<\/style>/);
if (style === null || !source.includes('viewBox="0 0 160 200"'))
	throw new Error(
		"Portal artwork changed structure; review the static export policy.",
	);
const css = postcss.parse(style[1]);
css.walkAtRules((rule) => rule.remove());
css.walkDecls(/^animation(?:-|$)/, (declaration) => declaration.remove());
css.walkComments((comment) => comment.remove());
css.walkRules((rule) => {
	if (rule.nodes.length === 0) rule.remove();
});
const staticLogo = source
	.replace(/<style>[\s\S]*?<\/style>/, `<style>${css.toString()}</style>`)
	.replace(/<!--[\s\S]*?-->/g, "")
	// Keep the tall portal centered on a square with room for the surrounding sparks.
	.replace('viewBox="0 0 160 200"', 'viewBox="-32 -12 224 224"')
	.replace('width="100%"', 'width="224"')
	.replace('height="100%"', 'height="224"')
	.replace(/\s+aria-hidden="true"/, "");
const svg = await format(
	`<!-- Generated by npm run generate:branding; edit assets/branding/portal.svg. -->\n${staticLogo}`,
	{ parser: "html", useTabs: true },
);
const render = (size) =>
	new Resvg(svg, {
		fitTo: { mode: "width", value: size },
		font: { loadSystemFonts: false },
	})
		.render()
		.asPng();
const png = render(1024);
const ico = png2icons.createICO(png, png2icons.BICUBIC2, 0, false, true);
const icns = png2icons.createICNS(png, png2icons.BICUBIC2, 0);
if (ico === null) throw new Error("Windows icon export failed.");
if (icns === null) throw new Error("macOS icon export failed.");

const outputs = new Map([
	["assets/branding/portal-static.svg", Buffer.from(svg)],
	["assets/branding/icon.png", render(512)],
	["assets/branding/icon.ico", ico],
	["assets/branding/icon.icns", icns],
	["apps/holtburger-3d/public/favicon.svg", Buffer.from(svg)],
	[
		"apps/holtburger-cli/dist/io.github.merklejerk.holtburger-cli.svg",
		Buffer.from(svg),
	],
]);
for (const [path, expected] of outputs) {
	const destination = new URL(path, repository);
	if (check) {
		const actual = await readFile(destination);
		if (!actual.equals(expected))
			throw new Error(
				`${path} is stale. Run npm run generate:branding in apps/holtburger-3d.`,
			);
	} else {
		await writeFile(destination, expected);
	}
	console.log(
		`${check ? "Verified" : "Generated"} ${fileURLToPath(destination)}`,
	);
}
