import { readFile, writeFile } from "node:fs/promises";
import { format } from "prettier";

// Input: the read-only apps/holtburger-tools/sql/housing-payment-icons.sql query, as raw TSV.
const input = process.argv[2];
if (!input) throw new Error("Expected a housing payment icon TSV path.");
const rows = (await readFile(input, "utf8")).trimEnd().split(/\r?\n/);
const seen = new Set<number>();
const entries = rows.map((line, index) => {
	const columns = line.split("\t");
	if (columns.length !== 7)
		throw new Error(`Row ${index + 1}: expected seven columns.`);
	const [wcid, name, base, itemType, effects, overlay, underlay] = columns;
	const number = (value: string): number => {
		if (!/^\d+$/.test(value) || Number(value) > 0xffffffff)
			throw new Error(`Row ${index + 1}: invalid unsigned value ${value}.`);
		return Number(value);
	};
	const id = number(wcid);
	if (seen.has(id)) throw new Error(`Duplicate payment WCID ${id}.`);
	seen.add(id);
	if (number(base) >>> 24 !== 6)
		throw new Error(`WCID ${id}: invalid icon DID.`);
	return `// ${name}\n[${id}, ${number(base)}, ${number(itemType)}, ${number(effects)}, ${overlay === "NULL" ? "null" : number(overlay)}, ${underlay === "NULL" ? "null" : number(underlay)}],`;
});
const output = await format(
	`// Generated by npm run generate:housing-payment-icons.\n// Source: apps/holtburger-tools/sql/housing-payment-icons.sql, default ACE World.\n// Reference artwork is presentation data; live exact-WCID artwork takes precedence.\nimport type { UiIconSpec } from "../app/ui-icon-source";\n\n/** Exact template composition inputs, independent of inventory membership. */\nconst references: readonly (readonly [wcid: number, base: number, itemType: number, uiEffects: number, overlay: number | null, underlay: number | null])[] = [\n${entries.join("\n")}\n];\n\n/** Bundled default-world artwork for every disclosed buy/rent payment template. */\nexport const housingPaymentIcons: ReadonlyMap<number, UiIconSpec> = new Map(references.map(([wcid, base, itemType, uiEffects, overlay, underlay]) => [wcid, {kind: "item", base, itemType, uiEffects, overlay, underlay}]));\n`,
	{ parser: "typescript", useTabs: true },
);
await writeFile(
	new URL("../src/client/client-housing-payment-icons.ts", import.meta.url),
	output,
);
