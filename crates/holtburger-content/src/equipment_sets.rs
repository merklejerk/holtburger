#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn set_names_preserve_shared_weapon_weaves_and_unknown_ids() {
        assert_eq!(equipment_set_name(13), Some("Soldier's"));
        assert_eq!(equipment_set_name(53), equipment_set_name(67));
        assert_eq!(equipment_set_name(54), equipment_set_name(57));
        assert_eq!(equipment_set_name(0), None);
        assert_eq!(equipment_set_name(i32::MAX), None);
    }
}
